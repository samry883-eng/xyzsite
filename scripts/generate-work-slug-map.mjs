/**
 * Regenerate lib/work-slug-map.mjs from the live projects catalog.
 *
 * middleware.js rewrites /work/{slug}/ to /work/{category}/{slug}/index.html
 * using WORK_SLUG_TO_CATEGORY. That map used to be hand-maintained, so any
 * project added through the CMS resolved to a 404 until someone edited it by
 * hand. This runs in the build so CMS projects work on the next deploy.
 *
 * Existing entries are merged, not replaced: if the catalog fetch ever falls
 * back to a thin source, we must not drop slugs that currently resolve.
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { fetchProjectsCatalog } from './projects-catalog-lib.mjs';
import { PROJECT_CATEGORIES } from '../lib/projects-store.mjs';
import {
  WORK_SLUG_TO_CATEGORY as EXISTING,
  WORK_CATEGORIES,
  WORK_RESERVED_SEGMENTS,
} from '../lib/work-slug-map.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, '..');
const dest = path.join(root, 'lib', 'work-slug-map.mjs');

const { catalog, source } = await (async () => {
  const c = await fetchProjectsCatalog(root);
  return c?.projects ? { catalog: c, source: 'catalog' } : { catalog: c, source: 'none' };
})();

const merged = { ...EXISTING };
let added = 0;
for (const p of catalog?.projects || []) {
  if (!p?.slug || !p?.category) continue;
  if (!PROJECT_CATEGORIES.includes(p.category)) continue;
  if (merged[p.slug] !== p.category) {
    if (!(p.slug in merged)) added += 1;
    merged[p.slug] = p.category;
  }
}

const slugs = Object.keys(merged).sort();
const body = `// Auto-generated by scripts/generate-work-slug-map.mjs — do not edit
export const WORK_SLUG_TO_CATEGORY = {
${slugs.map((s) => `  ${JSON.stringify(s)}: ${JSON.stringify(merged[s])}`).join(',\n')}
};
export const WORK_CATEGORIES = ${JSON.stringify(WORK_CATEGORIES)};
export const WORK_RESERVED_SEGMENTS = ${JSON.stringify(WORK_RESERVED_SEGMENTS)};
`;

fs.writeFileSync(dest, body, 'utf8');
console.log(`[work-slug-map] ${slugs.length} slugs (${added} new) from ${source}`);
